/** Logo (list se stonkem v zaobleném obdélníku) jako vložené SVG. */
export function Logo({ variant = 'barevne', height = 32, title = 'Logo', className }: Props) {
  const a11y = title
    ? { role: 'img', 'aria-label': title }
    : { 'aria-hidden': true as const, focusable: 'false' as const };
  const mono = variant === 'cerne';
  const c = mono ? null : COLORS[variant];
  const ink = c?.frame ?? 'currentColor';

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 75.1 54.3"
      height={height}
      className={['logo', className].filter(Boolean).join(' ')}
      {...a11y}
    >
      {title && <title>{title}</title>}
      <rect
        x={FRAME.x}
        y={FRAME.y}
        width={FRAME.width}
        height={FRAME.height}
        rx={FRAME.rx}
        fill="none"
        stroke={ink}
        strokeWidth={FRAME.strokeWidth}
      />
      {c ? (
        <>
          <path d={STEM} fill={c.frame} />
          <path d={LEAF} fill={c.leaf} />
          <path d={VEIN} fill={c.vein} />
        </>
      ) : (
        <>
          <path d={MONO_STEM} fill={ink} />
          <path d={MONO_LEAF} fill={ink} fillRule="evenodd" />
        </>
      )}
    </svg>
  );
}
